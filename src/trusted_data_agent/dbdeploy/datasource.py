"""
datasource — pluggable demo-data sources for the deployment.

The Databricks industry models ship **no** row-level data (the ``samples/*.csv``
described in their readme are generated by Databricks' own deployment process,
not committed to the repo).  So the default source here is a deterministic,
seeded **synthetic generator** that respects datatypes, PK uniqueness, and FK
referential validity — the same job Databricks' agent does, but zero-LLM and
reproducible.  A :class:`ShippedCsvDataSource` slots in unchanged if real CSVs
are ever available.

Pure: ``generate(model)`` does no I/O.  ShippedCsvDataSource is handed already
fetched CSV text (the fetch itself lives in industry_model_source).
"""

from __future__ import annotations

import random
import re
from abc import ABC, abstractmethod
from datetime import date, datetime, timedelta
from decimal import Decimal
from typing import Any, Dict, List, Optional, Tuple

from .csv_coerce import NULL_TOKENS, coerce_csv
from .physical_model import PhysicalModel, PhysTable
from .types import LoadPlan

# Key for a table across the model = (database_name, table_name)
TableKey = Tuple[str, str]


class DataSource(ABC):
    """Produces demo rows per table, keyed by (database_name, table_name)."""

    @abstractmethod
    def generate(self, model: PhysicalModel) -> Dict[TableKey, List[Dict[str, Any]]]:
        ...


# ── synthetic ──────────────────────────────────────────────────────────────────

_BASE_DATE = date(2020, 1, 1)
_BASE_TS = datetime(2020, 1, 1, 0, 0, 0)


class SyntheticDataSource(DataSource):
    """Deterministic, FK-aware synthetic row generator.

    Tables are generated in FK-dependency order (parents before children) so
    child FK columns can sample real parent key values.  Same (model, rows_per_table,
    seed) → byte-identical output.
    """

    def __init__(self, rows_per_table: int = 20, seed: int = 1469):
        self.rows_per_table = rows_per_table
        self.seed = seed

    @staticmethod
    def parent_db_resolver(model: PhysicalModel):
        """(domain, table) → the database that table is deployed in.

        Resolving a FK's parent BY DOMAIN breaks on a flattened model: there the
        database list collapses to one entry with ``domain=""`` while every FKRef
        still names its logical domain — so the lookup missed, ``fk_map`` stayed
        empty, and FK columns were filled with random integers (no join in the
        deployed demo data ever matched).  The table itself knows where it lives.
        """
        by_table = {(t.domain, t.name): t.database_name for t in model.tables}
        by_domain = {d.domain: d.name for d in model.databases}

        def resolve(domain: str, table: str) -> Optional[str]:
            return by_table.get((domain, table)) or by_domain.get(domain)
        return resolve

    def fk_map_for(self, model: PhysicalModel) -> Dict[Tuple[str, str, str], Tuple[str, str, str]]:
        """resolved FK source column -> (parent_db, parent_table, parent_column)"""
        resolve = self.parent_db_resolver(model)
        fk_map: Dict[Tuple[str, str, str], Tuple[str, str, str]] = {}
        for fk in model.fks:
            pdb = resolve(fk.tgt_domain, fk.tgt_table)
            if pdb:
                fk_map[(fk.src_domain, fk.src_table, fk.src_column)] = (pdb, fk.tgt_table, fk.tgt_column)
        return fk_map

    def generate(self, model: PhysicalModel) -> Dict[TableKey, List[Dict[str, Any]]]:
        fk_map = self.fk_map_for(model)
        order = self._topo_order(model)
        generated: Dict[TableKey, List[Dict[str, Any]]] = {}

        for table in order:
            key = (table.database_name, table.name)
            rng = random.Random(f"{self.seed}:{key[0]}.{key[1]}")
            rows = self._gen_table(table, rng, fk_map, generated)
            generated[key] = rows
        return generated

    def _topo_order(self, model: PhysicalModel, db_by_domain: Optional[Dict[str, str]] = None) -> List[PhysTable]:
        """Parents before children (FK dependency order); cycle-tolerant."""
        resolve = self.parent_db_resolver(model)
        by_key: Dict[TableKey, PhysTable] = {(t.database_name, t.name): t for t in model.tables}
        deps: Dict[TableKey, set] = {k: set() for k in by_key}
        for fk in model.fks:
            sdb = resolve(fk.src_domain, fk.src_table)
            pdb = resolve(fk.tgt_domain, fk.tgt_table)
            src_key = (sdb, fk.src_table)
            tgt_key = (pdb, fk.tgt_table)
            if src_key in by_key and tgt_key in by_key and src_key != tgt_key:
                deps[src_key].add(tgt_key)

        ordered: List[PhysTable] = []
        visited: set = set()
        temp: set = set()

        def visit(k: TableKey):
            if k in visited:
                return
            if k in temp:  # cycle — break it
                return
            temp.add(k)
            for dep in sorted(deps.get(k, ()), key=lambda x: (x[0] or "", x[1] or "")):
                visit(dep)
            temp.discard(k)
            visited.add(k)
            ordered.append(by_key[k])

        for k in sorted(by_key, key=lambda x: (x[0] or "", x[1] or "")):
            visit(k)
        return ordered

    def _gen_table(self, table, rng, fk_map, generated) -> List[Dict[str, Any]]:
        rows: List[Dict[str, Any]] = []
        seen_pk: set = set()
        pk_set = set(table.pk_columns)

        for i in range(self.rows_per_table):
            row: Dict[str, Any] = {}
            for col in table.columns:
                fk_target = fk_map.get((table.domain, table.name, col.name))
                if fk_target:
                    row[col.name] = self._sample_fk(fk_target, generated, rng)
                elif col.name in pk_set:
                    row[col.name] = self._gen_pk_value(col, i)
                else:
                    row[col.name] = self._gen_value(col.dbx_type, rng, i, col.name)
            # guarantee PK-tuple uniqueness
            if table.pk_columns:
                row = self._ensure_unique_pk(row, table.pk_columns, seen_pk, i)
            rows.append(row)
        return rows

    def _sample_fk(self, fk_target, generated, rng):
        pdb, ptable, pcol = fk_target
        parent_rows = generated.get((pdb, ptable)) or []
        vals = [r.get(pcol) for r in parent_rows if r.get(pcol) is not None]
        return rng.choice(vals) if vals else None

    def _gen_pk_value(self, col, i: int):
        t = (col.dbx_type or "").upper()
        if t.startswith(("BIGINT", "INT", "SMALLINT", "TINYINT", "LONG")):
            return i + 1
        return f"{col.name}_{i + 1}"

    def _ensure_unique_pk(self, row, pk_columns, seen_pk, i):
        tup = tuple(row[c] for c in pk_columns)
        if tup not in seen_pk:
            seen_pk.add(tup)
            return row
        # bump first integer PK column until unique; else suffix a string PK col
        for c in pk_columns:
            if isinstance(row.get(c), int):
                while tuple(row[col] for col in pk_columns) in seen_pk:
                    row[c] += 1
                seen_pk.add(tuple(row[col] for col in pk_columns))
                return row
        for c in pk_columns:
            if isinstance(row.get(c), str):
                row[c] = f"{row[c]}_{i}"
                break
        seen_pk.add(tuple(row[col] for col in pk_columns))
        return row

    def _gen_value(self, dbx_type: str, rng, i: int, col_name: str):
        t = (dbx_type or "STRING").upper().strip()
        if t in ("BOOLEAN", "BOOL"):
            return rng.choice([0, 1])
        # Integer family — bound by the Teradata target range so the value can
        # never overflow (TINYINT→BYTEINT max 127, SMALLINT max 32767).  Order
        # matters: check the narrow types before the generic "INT" prefix.
        if t.startswith("TINYINT"):
            return rng.randint(0, 127)
        if t.startswith("SMALLINT"):
            return rng.randint(0, 32767)
        if t.startswith(("BIGINT", "LONG")):
            return rng.randint(1, 1_000_000)
        if t.startswith(("INT", "INTEGER")):
            return rng.randint(1, 100_000)
        if t.startswith(("DOUBLE", "FLOAT", "REAL")):
            return round(rng.uniform(0, 10000), 4)
        if t.startswith(("DECIMAL", "NUMERIC", "NUMBER")):
            return self._gen_decimal(t, rng)
        if t == "DATE":
            return _BASE_DATE + timedelta(days=rng.randint(0, 2000))
        if t.startswith("TIMESTAMP"):
            return _BASE_TS + timedelta(seconds=rng.randint(0, 60_000_000))
        if t.startswith(("ARRAY", "MAP", "STRUCT")):
            return "[]"
        return f"{col_name}_{i + 1}"

    @staticmethod
    def _gen_decimal(t: str, rng) -> Decimal:
        """Generate a DECIMAL that fits the column's precision/scale.

        ``DECIMAL(p,s)`` holds values with at most ``p`` total digits and ``s``
        after the point, so the integer part must be ``< 10**(p-s)``.  Parsing
        the precision prevents the numeric-overflow (Teradata Error 2616) that a
        fixed 0–100000 range causes for small-scale columns like DECIMAL(5,2).
        """
        m = re.search(r"\(\s*(\d+)\s*,\s*(\d+)\s*\)", t)
        p, s = (int(m.group(1)), int(m.group(2))) if m else (18, 2)
        int_digits = max(1, p - s)
        int_part = rng.randint(0, 10 ** int_digits - 1)
        if s > 0:
            frac = rng.randint(0, 10 ** s - 1)
            return Decimal(f"{int_part}.{str(frac).zfill(s)}")
        return Decimal(int_part)


# ── shipped CSV ─────────────────────────────────────────────────────────────────

class ShippedCsvDataSource(DataSource):
    """Coerce already-fetched CSV text (one per table) into typed rows.

    ``csv_by_table`` maps (database_name, table_name) → CSV text.  The actual
    fetch lives in ``industry_model_source.fetch_sample_csv`` (I/O kept separate).
    """

    def __init__(self, csv_by_table: Dict[TableKey, str], null_tokens=NULL_TOKENS):
        self._csv = csv_by_table
        self._null_tokens = null_tokens

    def generate(self, model: PhysicalModel) -> Dict[TableKey, List[Dict[str, Any]]]:
        out: Dict[TableKey, List[Dict[str, Any]]] = {}
        # Need the Teradata column types per table → reuse the converter's load plan.
        from .converter import resolve_dialect
        emitter = resolve_dialect("teradata")
        conv = emitter.convert(model, logical_db_name=f"{model.industry}_{model.flavour}")
        types_by_table = {
            (s.target_database, s.target_table): s.columns for s in conv.load.tables
        }
        for key, csv_text in self._csv.items():
            cols = types_by_table.get(key, [])
            out[key] = coerce_csv(csv_text, cols, self._null_tokens)
        return out


# ── attach helper ─────────────────────────────────────────────────────────────

def populate_load_plan(
    load_plan: LoadPlan,
    model: PhysicalModel,
    source: Optional[DataSource] = None,
) -> LoadPlan:
    """Generate rows via ``source`` (default synthetic) and attach to each spec."""
    source = source or SyntheticDataSource()
    data = source.generate(model)
    for spec in load_plan.tables:
        spec.records = data.get((spec.target_database, spec.target_table), [])
    return load_plan
